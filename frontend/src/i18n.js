export function translate(lang, path) {
  const parts = path.split(".");
  let cur = dict[lang] || dict.en;
  for (const p of parts) {
    cur = cur?.[p];
    if (cur === undefined) break;
  }
  if (cur === undefined) {
    cur = dict.en;
    for (const p of parts) cur = cur?.[p];
  }
  return cur ?? path;
}

